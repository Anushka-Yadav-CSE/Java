// A program to print the natural numbers from 1 to 10.
public class NaturalNumbers {
    public static void main(String[] args) {
        // Output
        System.out.println("Natural numbers from 1 to 10: ");
        // For loop
        for (int i = 1; i <= 10; i++) {
            // Output
            System.out.println(i);
        }
    }
}